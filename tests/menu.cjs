const assert = require('node:assert/strict');
module.exports = async function checkMenu(page) {
  await page.setViewportSize({ width: 1440, height: 1000 });
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'false');
  assert.equal(await page.locator('#sidebar-nav').isVisible(), false);
  await page.locator('#menu-toggle').click();
  const items = page.locator('nav button');
  await items.last().waitFor();
  await page.waitForTimeout(650);
  const bounds = await items.evaluateAll(items => items.map(el => { const r=el.getBoundingClientRect(); return {top:r.top,bottom:r.bottom}; }));
  assert.ok(bounds.every((r,i) => !i || r.top > bounds[i-1].bottom));
  const first=items.first();
  const before=await first.boundingBox();
  await first.hover();
  await page.waitForTimeout(260);
  assert.ok((await first.boundingBox()).width > before.width * 1.04);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'false');
  await require('./navigate.cjs')(page, 'Моя анкета');
  await page.locator('[name=name]').fill('Несохранённый текст');
  await page.locator('#menu-toggle').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('[name=name]').inputValue(), 'Несохранённый текст');
  await page.locator('h1').click();
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'false');
  await page.evaluate(() => window.scrollTo({top:500,behavior:'instant'}));
  assert.ok(await page.locator('.global-navigation').evaluate(el => el.getBoundingClientRect().bottom <= 0));
  await page.reload();
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'false');
  await page.setViewportSize({ width: 390, height: 844 });
  await require('./navigate.cjs')(page, 'Личный план');
  await page.locator('#menu-toggle').click();
  await page.waitForTimeout(650);
  const last=await items.last().boundingBox();
  assert.ok(last.x >= 0 && last.x+last.width <= 390);
  await page.keyboard.press('Escape');
  await require('./navigate.cjs')(page, 'Мой маршрут');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  console.log('PASS: vertical oval menu, hover growth, keyboard and outside close, preserved draft, scrolling and mobile navigation');
};
