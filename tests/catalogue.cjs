const assert = require('node:assert/strict');
module.exports = async function checkCatalogue(browser, baseURL) {
  const context = await browser.newContext();
  const page = await context.newPage();
  await page.goto(baseURL);
  const navigate = name => page.locator('nav').getByRole('button', {name, exact:true}).click();
  await navigate('Учёба и работа');
  assert.equal(await page.locator('#catalogue-list article').count(),30);
  await page.locator('#catalogue-search').fill('тестир');
  assert.ok(await page.locator('#catalogue-list article').count() >= 2);
  await page.locator('#catalogue-search').fill('нет-такого-направления');
  await page.getByText('Ничего не найдено.',{exact:false}).waitFor();
  await page.locator('#catalogue-reset').click();
  await page.locator('[data-filter="Работа"]').click();
  assert.equal(await page.locator('#catalogue-list article').count(),10);
  await require('./choose.cjs')(page,'#catalogue-city','Онлайн');
  assert.equal(await page.locator('#catalogue-list article').count(),3);
  await page.locator('#catalogue-reset').click();
  await page.locator('[data-apply="8"]').click();
  await navigate('Личный план');
  const template=page.locator('[data-template="1"]');
  await template.click();
  assert.equal(await page.locator('[data-template="1"]').isDisabled(),true);
  const goalsBefore=await page.locator('[data-goal]').count();
  await page.reload();
  await navigate('Личный план');
  assert.equal(await page.locator('[data-goal]').count(),goalsBefore);
  await navigate('Мои наставники');
  assert.equal(await page.locator('.mentor-profile').count(),10);
  const first=page.locator('.mentor-profile').first();
  await first.locator('summary').click();
  const future=new Date(Date.now()+3*86400000).toISOString().slice(0,16);
  await first.locator('input').fill(future);
  await first.locator('button').click();
  assert.equal(await page.locator('.row').filter({hasText:'локальная заявка'}).count(),1);
  await navigate('Мост в будущее');
  assert.equal(await page.locator('[data-track]').count(),6);
  await page.locator('[data-track="2"]').click();
  assert.equal(await page.locator('#catalogue-topic').inputValue(),'Творчество');
  await navigate('Помощь сейчас');
  assert.equal(await page.locator('.resource').count(),12);
  await page.locator('.resource').first().locator('summary').click();
  assert.equal(await page.locator('.resource').first().locator('li').count(),3);
  await require('./choose.cjs')(page,'#role','Координатор');
  assert.equal(await page.locator('[data-request]').count(),0); // Examples never become personal requests.
  await page.getByRole('heading',{name:'Примеры ситуаций в очереди'}).waitFor();
  await require('./choose.cjs')(page,'#role','Куратор');
  await page.getByRole('heading',{name:'Примеры маршрутов участников'}).waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await context.close();
  console.log('PASS: rich catalogue search, combined filters, empty state, saved goals, mentors, booking, tracks, resources and separate staff examples');
};
